-- Blood Bond Bangladesh database setup for Supabase
-- Supabase SQL Editor-এ পুরো script চালান।
create table if not exists public.donors (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 80),
  blood text not null check (blood in ('A+','A-','B+','B-','AB+','AB-','O+','O-')),
  district text not null,
  upazila text not null,
  phone text not null,
  last_donation date,
  available boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.blood_requests (
  id bigint generated by default as identity primary key,
  blood text not null check (blood in ('A+','A-','B+','B-','AB+','AB-','O+','O-')),
  units text not null,
  needed_date date not null,
  hospital text not null,
  district text not null,
  contact text not null,
  details text,
  created_at timestamptz not null default now()
);

alter table public.donors enable row level security;
alter table public.blood_requests enable row level security;

-- Public donor directory: only donors who opted in (available=true) are shown.
drop policy if exists "Anyone can view available donors" on public.donors;
create policy "Anyone can view available donors"
on public.donors for select to anon, authenticated
using (available = true);

-- Public sign-up is enabled. Consent checkbox in the UI is not a substitute for moderation.
drop policy if exists "Anyone can register as donor" on public.donors;
create policy "Anyone can register as donor"
on public.donors for insert to anon, authenticated
with check (available in (true, false));

-- Emergency requests can be submitted, but are not publicly readable from this website.
drop policy if exists "Anyone can submit blood requests" on public.blood_requests;
create policy "Anyone can submit blood requests"
on public.blood_requests for insert to anon, authenticated
with check (true);

